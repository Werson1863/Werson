        w(f"| − Packaging | {p['packaging']:.2f} |")
        w(f"| − 3PL pick & pack | {p['fulfil']:.2f} |")
        w(f"| − Postage | {p['ship']:.2f} |")
        w(f"| − Payment fees | {u['pay']:.2f} |")
        w(f"| − Returns/refund allowance | {u['returns']:.2f} |")
        w(f"| **Contribution before ads = break-even CAC** | **{u['contrib']:.2f}** |")
        w(f"| Gross margin (net price − product − packaging) | {u['gm']:.0%} |")
        w(f"| Target CAC (keep 35% of contribution as profit) | {u['contrib']*0.65:.2f} |")
        w(f"| Contribution after target CAC | {u['contrib']*0.35:.2f} |\n")

        for sc, months in p["scenarios"].items():
            w(f"### {sc} scenario\n")
            w("| Month | AOV € | CPM € | CTR | CVR | CPA € | Ad spend € | New orders | Repeat orders | Revenue € (gross) | Contribution before ads € | Profit after ads & fixed € |")
            w("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
            customers = 0
            cum = 0.0
            for m, (aov, cpm, ctr, cvr, budget, share) in zip(MONTHS, months):
                u = per_order(p, aov, share)
                c = cpa(cpm, ctr, cvr)
                new = budget / c
                rep = customers * p["repeat_rate"][sc]
                orders = new + rep
                rev = orders * (aov + share * p["ship_fee"])
                contrib = orders * u["contrib"]
                profit = contrib - budget - FIXED_MONTHLY
                cum += profit
                customers += new
                w(f"| {m} | {aov:.0f} | {cpm:.1f} | {ctr:.1%} | {cvr:.1%} | {c:.1f} | {budget:,.0f} | {new:.0f} | {rep:.0f} | {rev:,.0f} | {contrib:,.0f} | {profit:,.0f} |")
