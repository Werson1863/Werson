def per_order(p, aov, share_below):
    net = aov / (1 + VAT)
    ship_rev = share_below * p["ship_fee"] / (1 + VAT)
    cogs = p["cogs_pct_gross"] * aov
    pay = PAY_PCT * (aov + share_below * p["ship_fee"]) + PAY_FIX
    returns = p["returns_pct_net"] * net
    var = cogs + p["packaging"] + p["fulfil"] + p["ship"] + pay + returns
    contrib = net + ship_rev - var
    gm = (net - cogs - p["packaging"]) / net
    return dict(net=net, ship_rev=ship_rev, cogs=cogs, pay=pay, returns=returns, var=var, contrib=contrib, gm=gm)


def cpa(cpm, ctr, cvr):
    return cpm / 1000 / ctr / cvr


